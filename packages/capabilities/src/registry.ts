const BY_KEY = new Map<CapabilityKey, CapabilityDefinition>(
  CAPABILITY_REGISTRY.map((definition) => [definition.key, definition]),
);

/** Definition for a capability key. Throws on an unknown key so callers cannot silently skip a capability. */
export function getCapabilityDefinition(key: CapabilityKey): CapabilityDefinition {
  const definition = BY_KEY.get(key);
  if (!definition) throw new Error(`Unknown capability: ${key}`);
  return definition;
}
